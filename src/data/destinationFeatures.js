// Convert a destination's features into a numeric vector for cosine similarity
export function toVector(features) {
  const categories = ["Relaxing Beach","Mountain Adventure","Cultural History",
    "Food Tour","Hill Stations","Spiritual","Budget ₹","Trending"];
  const regions = ["Europe","Asia","Americas","Africa","Oceania","Middle East"];
  const vibes = ["romantic","art","food","luxury","beach","spiritual","nature",
    "budget","adventure","city","wildlife","wellness"];
  const climates = ["temperate","tropical","cold","arid","mediterranean"];
  const budgets = ["low","mid","high"];

  return [
    ...categories.map(c => features.categories.includes(c) ? 1 : 0),
    ...regions.map(r => features.region === r ? 1 : 0),
    ...vibes.map(v => features.vibe.includes(v) ? 1 : 0),
    ...climates.map(c => features.climate === c ? 1 : 0),
    ...budgets.map(b => features.budget === b ? 1 : 0),
    features.solo ? 1 : 0,
    features.couple ? 1 : 0,
    features.family ? 1 : 0,
    features.popularity,
  ];
}
